def label_of(path):
    """ファイル名から画像の見出しを作る。作れないときは None。"""
    name = os.path.splitext(os.path.basename(path))[0]
    name = re.sub(r' \(\d+\)$', '', name)             # 「… (1)」の重複印
    page = re.search(r'_page-0*(\d+)$', name)
    if page:
        return f'{int(page.group(1))}ページ目'
    for s in LABEL_STRIP:
        name = name.replace(s, '')
    name = name.strip('_ 　')
    return name or None


