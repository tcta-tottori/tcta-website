      '取得ゲーム率が同じチームが 3 チーム以上なら、勝数の多い順にします。その中でまた 2 チームが並べば、直接対決の勝者を上にします。',
      'それでも決まらないとき（同率で直接対決も引き分けなど）は、くじ引きなどで決めます。',
