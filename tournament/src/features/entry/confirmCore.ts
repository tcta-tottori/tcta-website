/** 種目名の柔軟マッチング: 略称・正式名・部分一致など複数の戦略で比較 */
export function matchEventName(schedName: string, dbName: string): boolean {
  // 1. 完全一致
  if (schedName === dbName) return true;

  // 2. 空白・全角半角を正規化して比較
  const normA = schedName.replace(/[\u3000\s]+/g, '').replace(/[Ａ-Ｚａ-ｚ０-９]/g, c => String.fromCharCode(c.charCodeAt(0) - 0xFEE0)).toLowerCase();
  const normB = dbName.replace(/[\u3000\s]+/g, '').replace(/[Ａ-Ｚａ-ｚ０-９]/g, c => String.fromCharCode(c.charCodeAt(0) - 0xFEE0)).toLowerCase();
  if (normA === normB) return true;

  // 3. 部分一致（双方向）
  if (normA.length >= 2 && normB.length >= 2) {
    if (normB.includes(normA) || normA.includes(normB)) return true;
  }

  // 4. 日本語略称パターンマッチング
  for (const [abbrev, formal] of JP_ABBREV_PAIRS) {
    const normAbbrev = abbrev.toLowerCase();
    const normFormal = formal.replace(/[\u3000\s]+/g, '').toLowerCase();
    // schedName が略称で dbName が正式名
    if (normA === normAbbrev && normB === normFormal) return true;
    // schedName が正式名で dbName が略称
    if (normA === normFormal && normB === normAbbrev) return true;
  }

  // 5. コア部分を抽出して比較（シングルス/ダブルス/級/歳以上 を除去）
  const stripSuffix = (s: string) => s
    .replace(/シングルス|ダブルス/g, '')
    .replace(/級/g, '')
    .replace(/歳以上/g, '')
    .replace(/一般/g, '')
    .trim();
  const coreA = stripSuffix(normA);
  const coreB = stripSuffix(normB);
  if (coreA.length >= 2 && coreB.length >= 2 && coreA === coreB) return true;

  return false;
}

// ラウンド番号 → 時間割ラベル変換
function roundNumberToLabel(round: number, totalRounds: number): string {
  if (round === totalRounds) return 'F';
  if (round === totalRounds - 1) return 'SF';
  if (round === totalRounds - 2) return 'QF';
  return `${round}R`;
}

// 全種目の対戦順を時間割ベースで再計算
// === 確定後の実際の対戦に合わせて自動生成時間割を再編成する ===
// エントリーに欠場（不足）が出て確定された場合、不戦勝（BYE）を除いた
// 実際の試合だけで時間割を作り直す。手動でExcel取込した固定時間割は変更しない。
export async function maybeRegenerateSchedule(): Promise<void> {
  const { scheduleFileName, importedSchedule, scheduleConfig, currentTournamentId: tid } = useAppStore.getState();
  if (!tid) return;
  // 自動生成した時間割のみ再編成対象（取込済みの固定時間割は保持）
  if (importedSchedule.length === 0) return;
  if (!isAutoGeneratedSchedule(scheduleFileName)) return;

  // 既存の使用コート・生成条件（開始時刻・試合間隔）を引き継いで再生成する。
  // 条件を引き継がないと、確定のたびに時間割の刻みが変わってしまう。
  const tournament = await db.tournaments.where('tournamentId').equals(tid).first();
  const courts = await db.courts.where('tournamentId').equals(tid).toArray();
  const courtNames = courts
    .slice()
    .sort((a, b) => (a.order ?? 0) - (b.order ?? 0))
    .map(c => c.name);
  const startTime = scheduleConfig.startTime || tournament?.drawStartTime || '09:00';

  const result = await generateScheduleFromDraws(tid, {
    courtNames: courtNames.length > 0 ? courtNames : undefined,
    startTime,
    matchDuration: scheduleConfig.matchDuration || undefined,
    // 保存済みの条件よりドロー表の記載時刻を優先する。
    // （前回ずれた条件で保存されていても、確定のたびにドロー表どおりへ戻す）
    preferDrawBase: true,
  });
  if (result.items.length > 0) {
    useAppStore.getState().setImportedSchedule(result.items);
    useAppStore.getState().setScheduleFileName(AUTO_GENERATED_SCHEDULE_LABEL);
    useAppStore.getState().setScheduleConfig({ startTime: result.startTime, matchDuration: result.matchDuration });
  }
}

export async function recalculateGlobalMatchOrder(): Promise<void> {
  const { importedSchedule, currentTournamentId: tid } = useAppStore.getState();
  if (importedSchedule.length === 0 || !tid) return;

  // 全種目・全試合を取得
  const allEvents = await db.events.where('tournamentId').equals(tid).toArray();
  const allEventIds = allEvents.map(e => e.eventId);
  if (allEventIds.length === 0) return;
  const allMatches = await db.matches.where('eventId').anyOf(allEventIds).toArray();
  if (allMatches.length === 0) return;
  const allDraws = await db.draws.where('eventId').anyOf(allEventIds).toArray();
  const drawMap = new Map(allDraws.map(d => [d.eventId, d]));

  // コートを準備
  const existingCourts = await db.courts.where('tournamentId').equals(tid).toArray();
  const courtNameToId = new Map(existingCourts.map(c => [c.name, c.courtId]));
  for (const item of importedSchedule) {
    if (item.courtName && !courtNameToId.has(item.courtName)) {
      const courtId = `C-${Date.now()}-${item.courtName}`;
      await db.courts.add({
        tournamentId: tid, courtId, name: item.courtName,
        surface: '', isAvailable: true, currentMatchId: null,
        order: existingCourts.length + 1,
      });
      courtNameToId.set(item.courtName, courtId);
    }
  }

  // 種目+ラウンドごとの試合プール (playable試合をposition順にキューとして保持)
  // key: "eventId|roundLabel"
  const matchQueues = new Map<string, Match[]>();
  const walkoverMatches: Match[] = [];
  const orphanMatches: Match[] = [];

  for (const m of allMatches) {
    if (m.status === 'walkover') {
      walkoverMatches.push(m);
      continue;
    }
    const draw = drawMap.get(m.eventId);
    if (!draw) { orphanMatches.push(m); continue; }
    const totalRounds = Math.log2(draw.drawSize);
    const rLabel = roundNumberToLabel(m.round, totalRounds);
    const key = `${m.eventId}|${rLabel}`;
    if (!matchQueues.has(key)) matchQueues.set(key, []);
    matchQueues.get(key)!.push(m);
  }
  // 各キュー内をposition順にソート
  for (const [, q] of matchQueues) {
    q.sort((a, b) => a.position - b.position);
  }

  // 消費済みの試合（時刻一致で先に取り出した分をスキップするため）
  const consumed = new Set<number>();

  /** ドロー表に記載された、その試合の開始時刻（無ければ null） */
  const drawTimeOf = (m: Match): string | null => {
    const draw = drawMap.get(m.eventId);
    if (!draw) return null;
    if (m.round === 1) return draw.matchTimes?.[2 * m.position - 1] || null;
    return draw.roundMatchTimes?.[`R${m.round}-${m.position}`] || null;
  };

  /**
   * キューから次に割り当てる試合を取り出す。
   * ドロー表に開始時刻が記載されている試合は、その時刻と一致する枠へ優先的に入れる。
   * （順番だけで割り当てると、9:40開始の試合が9:00枠に入るなど、ドロー表と
   *   ずれた対戦が初回に並んでしまう）
   */
  const takeFromQueue = (key: string, itemStartTime: string): Match | null => {
    const queue = matchQueues.get(key);
    if (!queue) return null;
    // 1) この枠の時刻と同じドロー記載時刻を持つ、未消費の試合（position順）
    if (itemStartTime) {
      for (const m of queue) {
        if (m.id == null || consumed.has(m.id)) continue;
        if (drawTimeOf(m) === itemStartTime) {
          consumed.add(m.id);
          return m;
        }
      }
    }
    // 2) 見つからなければ、ドロー記載時刻が無い試合を順番に
    for (const m of queue) {
      if (m.id == null || consumed.has(m.id)) continue;
      if (drawTimeOf(m)) continue;
      consumed.add(m.id);
      return m;
    }
    // 3) それも無ければ未消費の先頭
    for (const m of queue) {
      if (m.id == null || consumed.has(m.id)) continue;
      consumed.add(m.id);
      return m;
    }
    return null;
  };

  // ラウンドラベルの代替キーを探す
  const findMatchKey = (eventId: string, roundLabel: string): string | null => {
    const key = `${eventId}|${roundLabel}`;
    if (matchQueues.has(key)) return key;
    // ラベル別名変換
    const aliases: string[] = [];
    if (/^\d+R$/.test(roundLabel)) aliases.push(`${eventId}|${roundLabel.replace('R', '回戦')}`);
    if (/^\d+回戦$/.test(roundLabel)) aliases.push(`${eventId}|${roundLabel.replace('回戦', 'R')}`);
    if (roundLabel === 'F') aliases.push(`${eventId}|決勝`);
    if (roundLabel === '決勝') aliases.push(`${eventId}|F`);
    if (roundLabel === 'SF') aliases.push(`${eventId}|準決勝`);
    if (roundLabel === 'QF') aliases.push(`${eventId}|準々決勝`);
    for (const alt of aliases) {
      if (matchQueues.has(alt)) return alt;
    }
    // ラウンドラベルなし（リーグや小規模種目）→ eventIdで始まるキューを探す
    if (!roundLabel) {
      for (const [k, q] of matchQueues) {
        if (k.startsWith(eventId + '|')) {
          if (q.some(m => m.id != null && !consumed.has(m.id))) return k;
        }
      }
    }
    return null;
  };

  // importedSchedule を順番に走査し、試合を1つずつ消費して順序を決定
  const ordered: { match: Match; courtName: string; startTime: string }[] = [];
  const unmatchedItems: string[] = [];

  for (const item of importedSchedule) {
    // 種目名 → eventId
    let matchedEventId: string | null = null;
    const resolvedName = SCHEDULE_CODE_TO_NAME[item.eventName.toLowerCase()] || item.eventName;
    for (const evt of allEvents) {
      if (matchEventName(resolvedName, evt.name)) {
        matchedEventId = evt.eventId;
        break;
      }
    }
    if (!matchedEventId) {
      unmatchedItems.push(`${item.eventName}(${item.roundLabel})`);
      continue;
    }

    // 対応するキューから次の試合を消費（ドロー記載時刻と一致する試合を優先）
    const qKey = findMatchKey(matchedEventId, item.roundLabel);
    if (!qKey) continue;
    const picked = takeFromQueue(qKey, item.startTime);
    if (!picked) continue;

    ordered.push({
      match: picked,
      courtName: item.courtName,
      startTime: item.startTime,
    });
  }

  if (unmatchedItems.length > 0) {
    console.warn('[スケジュール紐付け] マッチしなかった時間割:', [...new Set(unmatchedItems)].slice(0, 20));
  }

  // matchOrder を割り当て
  let order = 1;
  const updates: { id: number; matchOrder: number; courtId: string | null; scheduledTime: string | null }[] = [];

  for (const { match, startTime, courtName } of ordered) {
    if (!match.id) continue;
    updates.push({
      id: match.id,
      matchOrder: order++,
      courtId: courtNameToId.get(courtName) || null,
      scheduledTime: startTime || null,
    });
  }

  // キューに残った未消費の試合（スケジュールに載っていない分）
  const remaining: Match[] = [];
  for (const [, queue] of matchQueues) {
    for (const m of queue) {
      if (m.id != null && !consumed.has(m.id)) remaining.push(m);
    }
  }
  // walkover, orphan, remaining をまとめて末尾に追加
  const tail = [...remaining, ...walkoverMatches, ...orphanMatches].sort((a, b) => {
    if (a.eventId !== b.eventId) return a.eventId.localeCompare(b.eventId);
    if (a.round !== b.round) return a.round - b.round;
    return a.position - b.position;
  });
  for (const m of tail) {
    if (!m.id) continue;
    updates.push({
      id: m.id,
      matchOrder: order++,
      courtId: m.courtId,
      scheduledTime: m.scheduledTime,
    });
  }

  // 一括更新
  await db.transaction('rw', db.matches, async () => {
    for (const u of updates) {
      await db.matches.update(u.id, {
        matchOrder: u.matchOrder,
        courtId: u.courtId,
        scheduledTime: u.scheduledTime,
        updatedAt: Date.now(),
      });
    }
  });
}

/** 順位別トーナメントで、まだリーグの順位を入れていない（枠が全部空き） */
export const isUnfilledPlacement = (d?: Draw) => !!d?.slotSources?.length && !d.slots.some((s) => s.entryId);

/**
 * 1 種目のエントリーを確定して対戦表を作る（確認のダイアログ・進み具合の表示は呼び出し側）。
 * 順位別トーナメントでまだリーグの順位を入れていないときは何もせず false を返す
 */
export async function confirmEventCore(eventId: string, opts: { skipReorder?: boolean } = {}): Promise<boolean> {
  const tid = useAppStore.getState().currentTournamentId;
  // 取込済みドローの開始時刻がタイムゾーンぶんずれている場合は先に補正する
  if (tid) await repairShiftedDrawTimes(tid);
  const draw = await db.draws.where('eventId').equals(eventId).first();
  if (!draw || isUnfilledPlacement(draw)) return false;
  // 熱中症警戒時の試合形式を指定している場合は種目の回戦ルールへ付与する
  const heat = useAppStore.getState().heatRulePattern;
  if (heat.enabled) {
    const ev = await db.events.where('eventId').equals(eventId).first();
    if (ev?.id != null) {
      const defaultGames = ev.roundGameRules?.[0]?.games ?? ev.gameRules?.games ?? 6;
      await db.events.update(ev.id, { roundGameRules: applyHeatToRules(ev.roundGameRules, defaultGames, heat) });
    }
  }
  // ドローの内容から対戦表を組み直す（入力済みスコアは可能な限り引き継ぐ）
  await rebuildEventMatches(eventId);
  if (!opts.skipReorder) {
    await maybeRegenerateSchedule();
    await recalculateGlobalMatchOrder();
  }
  return true;
}
